export function defaultMailboxForDomain(domain) {
  const key = String(domain || "")
    .toLowerCase()
    .replace(/\.+$/, "")
    .trim();
  for (const [mailbox, domains] of Object.entries(SEED_DOMAINS_BY_MAILBOX)) {
    if (domains.includes(key)) return mailbox;
  }
  return getPrimaryMailbox();
}

export function allSeedDomains() {
  const seeded = Object.values(SEED_DOMAINS_BY_MAILBOX).flat();
  return [...new Set([...seeded, ...HISTORIC_SEED_DOMAINS])];
}

export function seedEntriesForMeta() {
  const primary = getPrimaryMailbox();
  const entries = [];
  for (const [mailbox, domains] of Object.entries(SEED_DOMAINS_BY_MAILBOX)) {
    for (const name of domains) {
      entries.push({ domain: name, mailbox, statusHint: "active" });
    }
  }
  for (const name of HISTORIC_SEED_DOMAINS) {
    entries.push({ domain: name, mailbox: primary, statusHint: "historic" });
  }
  return entries;
}

